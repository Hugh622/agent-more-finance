# ---------------------------------------------------------------------------
# 交付工程规范（判例沉淀）
# ---------------------------------------------------------------------------
@dataclass(frozen=True)
class EngStandards:
    ascii_filename: bool = True       # 交付文件一律 ASCII 文件名（中文长文件名曾致 send 失败）
    close_only_trigger: bool = True   # 执行线判决一律收盘口径，盘中击穿只披露不触发
    drift_errata_band: float = 0.005  # 快照漂移>0.5% 即进勘误带，须双源仲裁
    dual_source_must: bool = True     # 关键读数（指数/利率/汇率）≥2 独立通道互证
    code_mapping_check: bool = True   # 拉数必核 52 周高区间与代码映射（XOM 误标判例）
    stale_snapshot_guard: bool = True # 检索快照必须带日期验证（N225/BoJ 陈旧缓存判例）


ENG_STANDARDS: Final = EngStandards()


